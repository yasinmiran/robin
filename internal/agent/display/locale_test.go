package display

import (
	"os"
	"path/filepath"
	"slices"
	"testing"
)

func TestWithLocale(t *testing.T) {
	dir := t.TempDir()
	systemd := filepath.Join(dir, "locale.conf")
	debian := filepath.Join(dir, "locale")
	if err := os.WriteFile(systemd, []byte("# set by localectl\nLC_TIME=en_GB.UTF-8\nLANG=\"de_DE.UTF-8\"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(debian, []byte("#  File generated by update-locale\nLANG=en_DK.UTF-8\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	missing := filepath.Join(dir, "missing")
	base := []string{"HOME=/home/rj", "PATH=/usr/bin"}

	for _, tc := range []struct {
		name  string
		env   []string
		files []string
		want  string // the LANG entry withLocale must end with; "" for env unchanged
	}{
		{"LANG passed on", append(base, "LANG=fr_FR.UTF-8"), []string{systemd}, ""},
		{"LC_ALL passed on", append(base, "LC_ALL=fr_FR.UTF-8"), []string{systemd}, ""},
		{"LC_CTYPE passed on", append(base, "LC_CTYPE=C.UTF-8"), []string{systemd}, ""},
		{"systemd locale.conf", base, []string{systemd, debian}, "LANG=de_DE.UTF-8"},
		{"empty LANG counts as none", append(base, "LANG="), []string{missing, debian}, "LANG=en_DK.UTF-8"},
		{"no locale anywhere", base, []string{missing}, "LANG=C.UTF-8"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			env := slices.Clone(tc.env)
			got := withLocale(env, tc.files)
			if tc.want == "" {
				if !slices.Equal(got, tc.env) {
					t.Errorf("env changed to %q", got)
				}
				return
			}
			if len(got) != len(tc.env)+1 || got[len(got)-1] != tc.want {
				t.Errorf("got %q, want %q appended", got, tc.want)
			}
		})
	}
}
